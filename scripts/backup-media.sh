#!/usr/bin/env bash
# Off-site copy of uploaded ORIGINALS, encrypted with age, to Cloudflare R2.
#
#   scripts/backup-media.sh                 # sold originals not yet in R2 (default, nightly)
#   scripts/backup-media.sh --scope all     # every original of approved or sold media (watch the size!)
#   scripts/backup-media.sh --dry-run       # list what would be uploaded, upload nothing
#
# Cron (installed by scripts/server-setup.sh) at 03:15, after the database backup:
#   15 3 * * * /opt/micky/scripts/backup-media.sh >> /var/log/micky-backup.log 2>&1
#
# Why only SOLD originals by default: R2's free tier is 10 GB in total (database dumps
# included), while the VM holds up to ~150 GB of media. Originals a newsroom has paid for are
# the ones we owe someone, and they are usually a small share. Previews are NOT backed up: the
# worker can rebuild them from the originals. Everything else on the disk is covered only by
# Oracle's monthly boot-volume backup (manual, see docs/DEPLOYMENT.md section 9).
#
# Each file is encrypted to the same age public key(s) as the database dumps and streamed
# straight to R2 (`age | rclone rcat`): no plaintext copy, no temp file. Objects are named
# media/<storage key>.age and never change, so a run only uploads what is missing.
# The run stops before uploading if the bucket would exceed BACKUP_MEDIA_MAX_GB (default 8).
#
# Reads from .env: POSTGRES_USER, POSTGRES_DB, BACKUP_AGE_RECIPIENTS(_FILE), BACKUP_S3_*,
# BACKUP_MEDIA_MAX_GB. Needs: docker, age, rclone.
# MEDIA_MODE=native + MEDIA_DIR=/path reads files from a plain folder (testing, non-Docker).
set -euo pipefail
umask 077

# shellcheck source=scripts/lib.sh
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

SCOPE=sold
DRY_RUN=false
while [[ $# -gt 0 ]]; do
  case "$1" in
    --scope)
      [[ $# -ge 2 && "$2" =~ ^(sold|all)$ ]] || die "--scope must be sold or all"
      SCOPE="$2"
      shift 2
      ;;
    --dry-run) DRY_RUN=true; shift ;;
    -h | --help) sed -n '2,25p' "$0"; exit 0 ;;
    *) die "unknown option: $1" ;;
  esac
done

PG_USER="$(env_get POSTGRES_USER micky)"
PG_DB="$(env_get POSTGRES_DB micky)"
MAX_GB="$(env_get BACKUP_MEDIA_MAX_GB 8)"
[[ "$MAX_GB" =~ ^[0-9]+$ ]] || die "BACKUP_MEDIA_MAX_GB must be a whole number"
MEDIA_DIR="${MEDIA_DIR:-/data/storage}" # STORAGE_LOCAL_DIR inside the api container
mapfile -t AGE_ARGS < <(age_recipient_args)
[[ ${#AGE_ARGS[@]} -gt 0 ]] || exit 1

BACKUP_DIR="${BACKUP_DIR:-/var/backups/micky}"
mkdir -p "$BACKUP_DIR"
exec 9>"$BACKUP_DIR/.media-lock"
flock -n 9 || die "another media backup is still running"

# Streams one stored file to stdout.
read_media() {
  if [[ "${MEDIA_MODE:-compose}" == "native" ]]; then
    cat -- "$MEDIA_DIR/$1"
  else
    compose exec -T api cat -- "$MEDIA_DIR/$1"
  fi
}

if [[ "$SCOPE" == sold ]]; then
  where="m.id IN (SELECT media_id FROM orders WHERE status::text IN ('PAID', 'DISPUTED'))"
else
  where="m.status = 'APPROVED' OR m.id IN (SELECT media_id FROM orders WHERE status::text IN ('PAID', 'DISPUTED'))"
fi
# key<TAB>bytes, one line per original. Keys are generated by the API (storageKeys.original),
# never by users; they are still checked below before being used in a path.
# Not a process substitution: a failed query must stop the run, not look like "nothing to do".
rows="$(pg_tool psql --username="$PG_USER" --dbname="$PG_DB" -v ON_ERROR_STOP=1 -AtF $'\t' \
  -c "SELECT m.original_key, m.size_bytes FROM media m WHERE $where ORDER BY m.created_at")" ||
  die "could not list media from the database"
ROWS=()
[[ -z "$rows" ]] || mapfile -t ROWS <<<"$rows"

setup_rclone
MEDIA_DEST="${MEDIA_DEST:-${BACKUP_DEST%/postgres}/media}"
log "checking what is already in $MEDIA_DEST/"
declare -A UPLOADED=()
# A destination that does not exist yet is fine (first run); any other listing error is not,
# or every file would be uploaded again.
errors="$(mktemp)"
trap 'rm -f "$errors"' EXIT
listing="$(rclone lsf -R --files-only "$MEDIA_DEST" 2>"$errors")" || {
  grep -q "directory not found" "$errors" || die "could not list $MEDIA_DEST: $(cat "$errors")"
  listing=""
}
while IFS= read -r name; do
  [[ -n "$name" ]] && UPLOADED["$name"]=1
done <<<"$listing"

# Current bucket size (dumps + media), to stay inside the free tier.
bucket_bytes="$(rclone size --json "${MEDIA_DEST%/media}" 2>/dev/null | sed -n 's/.*"bytes":\([0-9]*\).*/\1/p')"
bucket_bytes="${bucket_bytes:-0}"

todo=()
todo_bytes=0
for row in "${ROWS[@]}"; do
  key="${row%%$'\t'*}"
  bytes="${row#*$'\t'}"
  [[ "$key" =~ ^originals/[A-Za-z0-9_-]+/[A-Za-z0-9_.-]+$ && "$key" != *..* ]] || {
    log "skipping unexpected storage key: $key"
    continue
  }
  [[ -n "${UPLOADED["$key.age"]-}" ]] && continue # .partial leftovers are simply re-uploaded
  todo+=("$key")
  todo_bytes=$((todo_bytes + bytes))
done

limit=$((MAX_GB * 1024 * 1024 * 1024))
log "${#ROWS[@]} originals in scope '$SCOPE', ${#todo[@]} to upload ($((todo_bytes / 1048576)) MB); bucket now $((bucket_bytes / 1048576)) MB of ${MAX_GB} GB allowed"
if ((bucket_bytes + todo_bytes > limit)); then
  die "uploading would pass BACKUP_MEDIA_MAX_GB=${MAX_GB}. Raise it (R2 bills \$0.015/GB-month above 10 GB) or move to STORAGE_DRIVER=s3"
fi
[[ "$DRY_RUN" == true ]] && { printf '%s\n' "${todo[@]}"; log "dry run: nothing uploaded"; exit 0; }

failed=0
for key in "${todo[@]}"; do
  # Upload under a temporary name and rename only when the whole pipe succeeded, so a failed
  # read can never leave a truncated object that later runs would count as backed up.
  if read_media "$key" | age "${AGE_ARGS[@]}" | rclone rcat "$MEDIA_DEST/$key.age.partial" &&
    rclone moveto "$MEDIA_DEST/$key.age.partial" "$MEDIA_DEST/$key.age"; then
    log "uploaded $key"
  else
    log "ERROR: could not back up $key (will retry next run)"
    failed=$((failed + 1))
  fi
done
((failed == 0)) || die "$failed file(s) failed"
log "media backup finished"
